def seed_reverse_blocks(db):
    if (
        db.execute("SELECT COUNT(*) AS c FROM reverse_blocks").fetchone()["c"] > 0
        or db.execute("SELECT COUNT(*) AS c FROM reverse_phrases").fetchone()["c"] > 0
    ):
        return
    for texts in BLOCKS:
        cur = db.execute("INSERT INTO reverse_blocks (status) VALUES ('active')")
        db.executemany(
            "INSERT OR IGNORE INTO reverse_phrases (text, decoys, status, block_id) VALUES (?, '[]', 'active', ?)",
            [(text, cur.lastrowid) for text in texts],
        )
    db.commit()

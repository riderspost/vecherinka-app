def seed_reverse_phrases(db):
    if db.execute("SELECT COUNT(*) AS c FROM reverse_phrases").fetchone()["c"] > 0:
        return
    for entry in PHRASES:
        db.execute(
            "INSERT OR IGNORE INTO reverse_phrases (text, decoys, status) VALUES (?, ?, 'active')",
            (entry["text"], json.dumps(entry["decoys"], ensure_ascii=False)),
        )
    db.commit()

def seed_prompts(db):
    existing = db.execute("SELECT COUNT(*) AS c FROM prompts").fetchone()["c"]
    if existing > 0:
        return
    db.executemany(
        "INSERT OR IGNORE INTO prompts (text) VALUES (?)",
        [(text,) for text in PROMPTS],
    )
    db.commit()
